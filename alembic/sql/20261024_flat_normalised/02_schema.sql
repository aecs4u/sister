);
CREATE INDEX ix_cadastral_unit_comune ON sister_next.cadastral_unit (comune_id);

-- Persons and legal entities seen anywhere: portal owners, document subjects, mortgage-inspection parties.
CREATE TABLE sister_next.subject (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_type text,
    fiscal_code text,
    name text NOT NULL,
    last_name text,
    first_name text,
    gender char(1),
    birth_date date,
    birth_comune_id bigint REFERENCES sister_next.comune (id),
    CONSTRAINT uq_subject_fiscal_code UNIQUE (fiscal_code),
