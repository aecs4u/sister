-- Step 2: the target schema, built next to the legacy one in `sister_next` and swapped in by 06_swap.sql.
--
-- Rules the design follows:
--   * flat: one typed column per fact. No JSON/text blobs, no EAV trees, no "x_json" copies of child rows,
--     no 1:1 side tables, no polymorphic "one of these three parents" columns.
--   * normalised: every repeated real-world thing (comune, cadastral unit, subject, right kind, office) exists once
--     and is referenced by a bigint key. Composite source text (shares, incomes, consistency, "NAME (PR)") is split
--     into typed columns. Dates are `date`/`timestamptz`, amounts are `numeric`.
--   * integrity in the database: every relation has a foreign key and an index, natural keys are unique
--     (NULLS NOT DISTINCT where a part may be missing), closed vocabularies are CHECKs, open ones are lookup tables.
--   * raw source payloads live in `sister_archive`, never in the working schema.
CREATE SCHEMA sister_next;
CREATE SCHEMA IF NOT EXISTS sister_archive;

