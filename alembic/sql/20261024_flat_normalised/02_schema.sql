-- A right is a kind (proprieta', usufrutto, ...) held for a share between two dates.
CREATE TABLE sister_next.ownership_right (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    right_kind_id bigint NOT NULL REFERENCES sister_next.right_kind (id),
    share_numerator integer,
    share_denominator integer,
    start_date date,
    end_date date,
    CONSTRAINT ck_ownership_right_share CHECK (
        (share_numerator IS NULL) = (share_denominator IS NULL) AND coalesce(share_denominator, 1) > 0
        AND coalesce(share_numerator, 0) >= 0
    ),
    CONSTRAINT ck_ownership_right_period CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
    CONSTRAINT uq_ownership_right UNIQUE NULLS NOT DISTINCT
        (right_kind_id, share_numerator, share_denominator, start_date, end_date)
);
CREATE INDEX ix_ownership_right_kind ON sister_next.ownership_right (right_kind_id);

