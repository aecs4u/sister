-- Schema adjustments found while porting the application to the flat layout. Idempotent: on a database built from the
-- corrected 20261024 DDL every step finds nothing to do.
--   * document.file_format is the file extension (PDF, P7M, XML, ZIP, DAT, ...): no closed list
--   * ownership_right: an end date before the start date is portal data to keep, not a reason to refuse a whole response
--   * the archived XML tree gets identity ids, so the writer that still stores the element tree does not have to invent them
--   * fields the Ocular importer fills (lien interest/expenses/currency, property area) get their columns back
--   * the uniqueness rules of the old layout that the first rebuild dropped: one extraction per (document, schema, run),
--     one XML attribute per (node, name), one form element / error per (visit, index), one property per (inspection, unit, number)
ALTER TABLE sister.document DROP CONSTRAINT IF EXISTS ck_document_file_format;
ALTER TABLE sister.ownership_right DROP CONSTRAINT IF EXISTS ck_ownership_right_period;

DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['document_xml_node', 'document_xml_attribute'] LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_attribute a
            WHERE a.attrelid = format('sister_archive.%I', t)::regclass AND a.attname = 'id' AND a.attidentity <> ''
        ) THEN
            EXECUTE format('ALTER TABLE sister_archive.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', t);
            EXECUTE format(
                'SELECT setval(pg_get_serial_sequence(%L, %L), coalesce((SELECT max(id) FROM sister_archive.%I), 0) + 1, false)',
                'sister_archive.' || t, 'id', t);
        END IF;
    END LOOP;
END $$;

ALTER TABLE sister.mortgage_inspection ADD COLUMN IF NOT EXISTS lien_semiannual_interest_rate text;
ALTER TABLE sister.mortgage_inspection ADD COLUMN IF NOT EXISTS lien_interest_eur integer;
ALTER TABLE sister.mortgage_inspection ADD COLUMN IF NOT EXISTS lien_expenses_eur integer;
ALTER TABLE sister.mortgage_inspection ADD COLUMN IF NOT EXISTS lien_foreign_currency text;
ALTER TABLE sister.mortgage_inspection_property ADD COLUMN IF NOT EXISTS area_sqm numeric;

DO $$
BEGIN
    IF to_regclass('sister_legacy.mortgage_inspection_liens') IS NOT NULL THEN
        UPDATE sister.mortgage_inspection m SET
            lien_semiannual_interest_rate = coalesce(m.lien_semiannual_interest_rate, l.semiannual_interest_rate),
            lien_interest_eur = coalesce(m.lien_interest_eur, l.interest_euro),
            lien_expenses_eur = coalesce(m.lien_expenses_eur, l.expenses_euro),
            lien_foreign_currency = coalesce(m.lien_foreign_currency, l.foreign_currency)
        FROM sister_legacy.mortgage_inspection_liens l WHERE l.extraction_id = m.extraction_id;
    END IF;
END $$;

DO $$
DECLARE r record;
BEGIN
    FOR r IN SELECT * FROM (VALUES
        ('sister.document_extraction', 'uq_document_extraction_run', 'UNIQUE (document_id, schema_name, run_id)'),
        ('sister.mortgage_inspection_property', 'uq_mortgage_property', 'UNIQUE NULLS NOT DISTINCT (inspection_id, unit_number, property_number)'),
        ('sister.page_visit_form_element', 'uq_page_visit_form_element', 'UNIQUE (page_visit_id, element_index)'),
        ('sister.page_visit_error', 'uq_page_visit_error', 'UNIQUE (page_visit_id, error_index)'),
        ('sister_archive.document_xml_attribute', 'uq_archive_xml_attribute', 'UNIQUE (node_id, name)')
    ) AS t (tbl, name, definition)
    LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = r.tbl::regclass AND conname = r.name) THEN
            EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I %s', r.tbl, r.name, r.definition);
        END IF;
    END LOOP;
END $$;
