"""Derive legacy database variables from <DB>_POSTGRES_DSN_<SUFFIX>.

The DSNs live once in the workspace files ``../.env.<profile>``; this project
selects them via ``POSTGRES_DATABASES`` and keeps reading its historical names.
Generated by the aecs4u.it environment consolidation; process variables win.
"""

from __future__ import annotations

import os
from pathlib import Path

_PROFILE_FILE = {"LOCALHOST": "development", "TEST": "testing", "STAGING": "staging", "PROD": "production"}
_ALIASES = {"dev": "development", "local": "development", "test": "testing", "stage": "staging", "prod": "production"}


def bridge_postgres_dsns(project_root: Path, aliases: dict[str, tuple[str, str | None]]) -> None:
    """Set ``legacy`` variables from their ``<DB>_POSTGRES_DSN_<SUFFIX>`` source.

    ``aliases`` maps legacy name -> (new name, profile it applies to or None).
    """
    try:
        from dotenv import dotenv_values
    except ImportError:  # pragma: no cover - dotenv is a declared dependency
        return
    workspace = project_root.parent
    selected = (
        os.environ.get("ENVIRONMENT")
        or os.environ.get("APP_ENV")
        or dotenv_values(project_root / ".env").get("ENVIRONMENT")
        or dotenv_values(workspace / ".env").get("ENVIRONMENT")
        or "development"
    ).strip().lower()
    selected = _ALIASES.get(selected, selected)
    cache: dict[str, dict] = {}
    for legacy, (new, only_profile) in aliases.items():
        if legacy in os.environ or (only_profile and only_profile != selected):
            continue
        value = os.environ.get(new)
        if not value:
            profile = _PROFILE_FILE[new.rsplit("_", 1)[1]]
            if profile not in cache:
                cache[profile] = dotenv_values(workspace / f".env.{profile}")
            value = cache[profile].get(new)
        if value:
            os.environ[legacy] = value
